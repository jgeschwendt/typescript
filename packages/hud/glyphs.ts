import { parse } from 'opentype.js';

// every outline is scaled so its box is this many CSS pixels tall
const height = 10;
const source = '@ibm/plex-mono/fonts/complete/woff/IBMPlexMono-SemiBold.woff';
const read = (path: string): Bun.BunFile => Bun.file(Bun.resolveSync(path, import.meta.dir));
const font = parse(await read(source).arrayBuffer());
const { version } = /"version": "(?<version>.+?)"/u.exec(
  await read('@ibm/plex-mono/package.json').text(),
)?.groups ?? { version: '' };
const round = (value: number): number => Number(value.toFixed(2));

// the glyphs scaled to one shared box, its top-left at the origin: one path, advance and ink width each
const outline = (chars: string): [string, { advance: number; path: string; width: number }][] => {
  const glyphs = Array.from(chars, (char) => [char, font.charToGlyph(char)] as const);
  const boxes = glyphs.map(([, glyph]) => glyph.getBoundingBox());
  const left = Math.min(...boxes.map(({ x1 }) => x1));
  const top = Math.max(...boxes.map(({ y2 }) => y2));
  const size = (height * font.unitsPerEm) / (top - Math.min(...boxes.map(({ y1 }) => y1)));
  const scale = size / font.unitsPerEm;
  const width = round((Math.max(...boxes.map(({ x2 }) => x2)) - left) * scale);
  return glyphs.map(([char, glyph]) => [
    char,
    {
      advance: round((glyph.advanceWidth ?? 0) * scale),
      path: glyph.getPath(-left * scale, top * scale, size).toPathData(2),
      width,
    },
  ]);
};

if (font.charToGlyph('✓').index === 0) {
  throw new Error('glyphs: the font has no ✓');
}
await Bun.write(
  `${import.meta.dir}/src/outlines.ts`,
  `// generated by glyphs.ts from IBM Plex Mono SemiBold (@ibm/plex-mono ${version}), SIL Open Font License 1.1; do not edit
// each glyph in CSS pixels on a ${height}px box, the digits sharing one box so every number sits on one baseline
const outlines = new Map(${JSON.stringify([...outline('0123456789'), ...outline('✓')])});

export { outlines };
`,
);
